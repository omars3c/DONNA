"""
Persistent Reminder Manager for D.O.N.N.A. (Windows Task Scheduler integration)
Supports:
  - Setting persistent reminders (fires even when Donna is closed)
  - Listing active upcoming reminders
  - Cancelling / Deleting specific reminders by ID or text
  - Cancelling all reminders
"""
from __future__ import annotations

import json
import os
import platform
import re
import shutil
import subprocess
import sys
import threading
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

_NO_WINDOW: int = getattr(subprocess, "CREATE_NO_WINDOW", 0x08000000)
_CNW: dict = (
    {"creationflags": _NO_WINDOW}
    if platform.system() == "Windows" else {}
)

_LOCK = threading.Lock()


def _base_dir() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys.executable).parent
    return Path(__file__).resolve().parent.parent


BASE_DIR = _base_dir()
REMINDERS_REGISTRY_PATH = BASE_DIR / "memory" / "reminders.json"


def _get_os() -> str:
    _sys = platform.system()
    if _sys == "Darwin":
        return "mac"
    if _sys == "Linux":
        return "linux"
    return "windows"


def _scripts_dir() -> Path:
    d = Path.home() / ".jarvis" / "reminders"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _sanitise(text: str, max_len: int = 200) -> str:
    return (
        text.replace("\\", "")
            .replace('"', "")
            .replace("'", "")
            .replace("\n", " ")
            .replace("\r", "")
            .strip()
    )[:max_len]


# ── Registry Operations (memory/reminders.json) ────────────────────────────────

def _load_registry() -> List[Dict[str, Any]]:
    with _LOCK:
        if not REMINDERS_REGISTRY_PATH.exists():
            return []
        try:
            data = json.loads(REMINDERS_REGISTRY_PATH.read_text(encoding="utf-8"))
            if isinstance(data, list):
                return data
            return []
        except Exception:
            return []


def _save_registry(items: List[Dict[str, Any]]) -> None:
    with _LOCK:
        REMINDERS_REGISTRY_PATH.parent.mkdir(parents=True, exist_ok=True)
        REMINDERS_REGISTRY_PATH.write_text(
            json.dumps(items, indent=2, ensure_ascii=False),
            encoding="utf-8"
        )


