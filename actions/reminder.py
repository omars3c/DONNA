def _schedule_windows(target_dt: datetime, task_name: str, script_path: Path, message: str) -> str:
    python_exe = Path(sys.executable)
    pythonw = python_exe.parent / "pythonw.exe"
    if pythonw.exists():
        python_exe = pythonw

    xml_path = _scripts_dir() / f"{task_name}.xml"
    xml_content = (
        '<?xml version="1.0" encoding="UTF-16"?>\n'
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">\n'
        '  <RegistrationInfo><Description>D.O.N.N.A. Reminder</Description></RegistrationInfo>\n'
        '  <Triggers><TimeTrigger>\n'
        f'    <StartBoundary>{target_dt.strftime("%Y-%m-%dT%H:%M:%S")}</StartBoundary>\n'
        '    <Enabled>true</Enabled>\n'
        '  </TimeTrigger></Triggers>\n'
        '  <Actions><Exec>\n'
        f'    <Command>{python_exe}</Command>\n'
        f'    <Arguments>"{script_path}"</Arguments>\n'
        '  </Exec></Actions>\n'
        '  <Settings>\n'
        '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>\n'
        '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n'
        '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n'
        '    <StartWhenAvailable>true</StartWhenAvailable>\n'
        '    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>\n'
        '    <Enabled>true</Enabled>\n'
        '  </Settings>\n'
        '  <Principals><Principal>\n'
        '    <LogonType>InteractiveToken</LogonType>\n'
        '    <RunLevel>LeastPrivilege</RunLevel>\n'
        '  </Principal></Principals>\n'
        '</Task>'
    )

    xml_path.write_text(xml_content, encoding="utf-16")

    result = subprocess.run(
        ["schtasks", "/Create", "/TN", task_name, "/XML", str(xml_path), "/F"],
        capture_output=True, text=True, **_CNW,
    )

    try:
        xml_path.unlink(missing_ok=True)
    except Exception:
        pass

    if result.returncode != 0:
        script_path.unlink(missing_ok=True)
        err = (result.stderr or result.stdout).strip()
        print(f"[Reminder] ❌ schtasks create error: {err}")
        return ""

    return task_name


def _delete_system_task(task_name: str) -> bool:
    """Delete scheduled task from Windows Task Scheduler or OS."""
    os_name = _get_os()
    if os_name == "windows":
        res = subprocess.run(
            ["schtasks", "/Delete", "/TN", task_name, "/F"],
            capture_output=True, text=True, **_CNW,
        )
        return res.returncode == 0
    elif os_name == "mac":
        plist_path = Path.home() / "Library" / "LaunchAgents" / f"com.jarvis.reminder.{task_name}.plist"
        subprocess.run(["launchctl", "unload", str(plist_path)], capture_output=True)
        plist_path.unlink(missing_ok=True)
        return True
    return True


# ── Main Entrypoint ───────────────────────────────────────────────────────────

def reminder(
    parameters: Optional[Any] = None,
    response=None,
    player=None,
    session_memory=None,
    **kwargs,
) -> str:
    """
    Manage reminders: set, list, cancel, cancel_all.
    parameters:
      action: set | list | cancel | cancel_all (default: set)
      date: YYYY-MM-DD
      time: HH:MM
      message: text description
      query / reminder_id: for cancellation
    """
    if isinstance(parameters, str):
        parameters_str = parameters.strip()
        if parameters_str.startswith("{") and parameters_str.endswith("}"):
            try:
                parsed = json.loads(parameters_str)
                params = parsed if isinstance(parsed, dict) else {"action": parameters_str}
            except Exception:
                params = {"action": parameters_str}
        else:
            params = {"action": parameters_str}
    elif isinstance(parameters, dict):
        params = dict(parameters)
    else:
        params = {}

    for k, v in kwargs.items():
        if k not in params or params[k] is None:
            params[k] = v

    action = (params.get("action") or "set").lower().strip()

    # ── 1. LIST REMINDERS ─────────────────────────────────────────────────────
    if action == "list":
        items = _load_registry()
        # Filter out past reminders
        now = datetime.now()
        active = []
        for it in items:
            try:
                dt = datetime.strptime(f"{it['date']} {it['time']}", "%Y-%m-%d %H:%M")
                if dt > now:
                    active.append(it)
            except Exception:
                pass

        _save_registry(active)
        if not active:
            return "У вас нет активных запланированных напоминаний."

        lines = ["⏰ Запланированные напоминания:\n"]
        for idx, it in enumerate(active, 1):
            lines.append(f"• #{idx} [{it['date']} {it['time']}]: {it['message']}")
        return "\n".join(lines)

    # ── 2. CANCEL ALL REMINDERS ───────────────────────────────────────────────
    if action in ("cancel_all", "delete_all", "clear_all"):
        items = _load_registry()
        count = 0
        for it in items:
            t_name = it.get("task_name", "")
            if t_name:
                _delete_system_task(t_name)
                s_path = _scripts_dir() / f"{t_name}.py"
                s_path.unlink(missing_ok=True)
                count += 1
        _save_registry([])
        return f"Все напоминания ({count} шт.) успешно отменены и удалены из системы."

    # ── 3. CANCEL SPECIFIC REMINDER ───────────────────────────────────────────
    if action in ("cancel", "delete", "remove"):
        target = str(params.get("reminder_id") or params.get("query") or params.get("message") or "").strip().lower()
        items = _load_registry()
        if not items:
            return "Нет активных напоминаний для отмены."

        removed = []
        remaining = []

        # Check numeric index #1, #2 or string match
        idx_match = re.search(r"\b(\d+)\b", target)
        target_idx = int(idx_match.group(1)) if idx_match else None

        for idx, it in enumerate(items, 1):
            is_match = False
            if target_idx is not None and idx == target_idx:
                is_match = True
            elif target and (target in str(it.get("message") or "").lower() or target in str(it.get("date") or "") or target in str(it.get("time") or "")):
                is_match = True

            if is_match or (not target and len(items) == 1):
                removed.append(it)
                t_name = it.get("task_name", "")
                if t_name:
                    _delete_system_task(t_name)
                    s_path = _scripts_dir() / f"{t_name}.py"
                    s_path.unlink(missing_ok=True)
            else:
                remaining.append(it)

        if removed:
            _save_registry(remaining)
            desc = ", ".join([f"'{r['message']}' ({r['date']} {r['time']})" for r in removed])
            return f"Напоминание успешно отменено и удалено из Windows: {desc}."

        # If user just said "cancel reminder" but multiple exist, cancel the earliest one
        if not target and items:
            first = items[0]
            t_name = first.get("task_name", "")
            if t_name:
                _delete_system_task(t_name)
                s_path = _scripts_dir() / f"{t_name}.py"
                s_path.unlink(missing_ok=True)
            _save_registry(items[1:])
            return f"Ближайшее напоминание '{first['message']}' ({first['date']} {first['time']}) успешно отменено."

        return f"Не удалось найти напоминание по запросу '{target}'. Скажите 'покажи напоминания', чтобы увидеть список."

    # ── 4. SET REMINDER ───────────────────────────────────────────────────────
    date_str = params.get("date", "").strip()
    time_str = params.get("time", "").strip()
    message  = params.get("message", "Reminder").strip()

    if not date_str or not time_str:
        return "Для установки напоминания укажите дату (YYYY-MM-DD) и время (HH:MM)."

    try:
        target_dt = datetime.strptime(f"{date_str} {time_str}", "%Y-%m-%d %H:%M")
    except ValueError:
        return "Не удалось распознать формат даты/времени. Используйте YYYY-MM-DD и HH:MM."

    if target_dt <= datetime.now():
        return "Указанное время уже прошло. Невозможно установить напоминание в прошлом."

    os_name    = _get_os()
    safe_msg   = _sanitise(message)
    task_name  = f"DONNAReminder_{target_dt.strftime('%Y%m%d_%H%M%S')}"

    try:
        script_path = _write_notify_script(task_name, safe_msg, os_name)
    except Exception as e:
        return f"Не удалось подготовить скрипт напоминания: {e}"

    try:
        if os_name == "windows":
            job_id = _schedule_windows(target_dt, task_name, script_path, safe_msg)
        else:
            job_id = task_name
    except Exception as e:
        script_path.unlink(missing_ok=True)
        print(f"[Reminder] ❌ Scheduling exception: {e}")
        return "Произошла ошибка при планировании напоминания в системе."

    if not job_id:
        return "Не удалось зарегистрировать напоминание в системном планировщике Windows."

    # Record in registry
    items = _load_registry()
    items.append({
        "id": len(items) + 1,
        "task_name": task_name,
        "date": date_str,
        "time": time_str,
        "message": safe_msg,
        "created_at": datetime.now().isoformat(),
    })
    _save_registry(items)

    if player:
        player.write_log(f"[Reminder] ✅ {date_str} {time_str} — {safe_msg[:40]}")

    friendly_time = target_dt.strftime("%d %B в %H:%M")
    return f"Напоминание успешно установлено на {friendly_time}: '{safe_msg}'. Оно сработает даже при закрытой программе."